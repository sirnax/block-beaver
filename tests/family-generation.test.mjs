test('writing, checking and re-planning are byte-stable and check writes nothing', async (t) => {
  const root = await repo(t);
  const loader = fakeLoader({ families: [family('gizmo', { generators: ['registry', 'index'] })], manifests: [manifest('gizmo', 'a')] });
  const first = await plan(root, loader);
  assert.deepEqual(first.outputs.map((output) => output.status), ['missing', 'missing']);
  assert.deepEqual(checkGeneration(first).map((item) => [item.rule, item.code, item.file, item.family]), [
    ['family-drift', 'output-missing', 'src/generated/gizmo.ts', 'gizmo'],
    ['family-drift', 'output-missing', '.blocks/index.json', undefined],
  ]);
  assert.deepEqual(await listing(root), [], 'check wrote nothing');

  const applied = await applyGeneration(root, first);
  assert.deepEqual(applied.written, ['src/generated/gizmo.ts', '.blocks/index.json']);
  const bytes = await Promise.all(first.outputs.map((output) => readFile(join(root, output.out), 'utf8')));
  assert.deepEqual(bytes, first.outputs.map((output) => output.expected));

  const second = await plan(root, loader);
  assert.deepEqual(second.outputs.map((output) => output.status), ['fresh', 'fresh']);
  assert.deepEqual(checkGeneration(second), []);
  assert.deepEqual((await applyGeneration(root, second)).written, []);
  assert.deepEqual(await Promise.all(first.outputs.map((output) => readFile(join(root, output.out), 'utf8'))), bytes);
});

test('a modified or deleted generated file is drift, and gen restores it', async (t) => {
  const root = await repo(t);
  const loader = fakeLoader({ families: [family('gizmo')], manifests: [manifest('gizmo', 'a')] });
  await applyGeneration(root, await plan(root, loader));
  const path = join(root, 'src/generated/gizmo.ts');
  const good = await readFile(path, 'utf8');

  await writeFile(path, good.replace('createRegistry(', 'tampered('));
  const stale = await plan(root, loader);
  assert.equal(stale.outputs[0].status, 'stale');
  assert.deepEqual(checkGeneration(stale).map((item) => item.code), ['output-stale']);
  assert.match(await readFile(path, 'utf8'), /tampered/, 'check left the edit alone');
  await applyGeneration(root, stale);
  assert.equal(await readFile(path, 'utf8'), good);

  await rm(path);
  assert.deepEqual(checkGeneration(await plan(root, loader)).map((item) => item.code), ['output-missing']);
});

