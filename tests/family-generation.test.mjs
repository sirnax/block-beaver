test('history is created, then left byte-identical until a manifest hash changes', async (t) => {
  const root = await repo(t);
  const state = { families: [family('gizmo', { generators: ['history'], registry: null })], manifests: [manifest('gizmo', 'a', { hash: 'sha256:aaa' })] };
  const first = await plan(root, fakeLoader(state), { now: new Date('2026-10-01T12:00:00.987Z') });
  assert.deepEqual(JSON.parse(first.outputs[0].expected), { schemaVersion: 1, entries: [{ date: '2026-10-01T12:00:00Z', label: null, source: 'gen', changes: [{ op: 'upsert', block: 'gizmo:a', hash: 'sha256:aaa' }] }] });
  await applyGeneration(root, first);
  const written = await readFile(join(root, '.blocks/history.json'), 'utf8');

  const again = await plan(root, fakeLoader(state), { now: new Date('2027-01-01T00:00:00Z') });
  assert.equal(again.outputs[0].status, 'fresh');
  assert.deepEqual(checkGeneration(again), []);
  assert.equal(again.outputs[0].expected, written);

  const changed = { families: state.families, manifests: [manifest('gizmo', 'a', { hash: 'sha256:bbb' }), manifest('gizmo', 'b', { hash: 'sha256:ccc' })] };
  const next = await plan(root, fakeLoader(changed), { now: new Date('2026-10-02T14:00:00+02:00'), label: 'cli label', config: { history: { label: 'configured' } } });
  assert.deepEqual(checkGeneration(next).map((item) => item.code), ['history-stale']);
  assert.equal(await readFile(join(root, '.blocks/history.json'), 'utf8'), written, 'check left history alone');
  const entry = JSON.parse(next.outputs[0].expected).entries[1];
  assert.deepEqual(entry, { date: '2026-10-02T12:00:00Z', label: 'cli label', source: 'gen', changes: [{ op: 'upsert', block: 'gizmo:a', hash: 'sha256:bbb' }, { op: 'upsert', block: 'gizmo:b', hash: 'sha256:ccc' }] });
  const configured = await plan(root, fakeLoader(changed), { now: NOW, config: { history: { label: 'configured' } } });
  assert.equal(JSON.parse(configured.outputs[0].expected).entries[1].label, 'configured');

  await applyGeneration(root, configured);
  const removed = await plan(root, fakeLoader({ families: state.families, manifests: [manifest('gizmo', 'b', { hash: 'sha256:ccc' })] }), { now: NOW });
  assert.deepEqual(JSON.parse(removed.outputs[0].expected).entries[2].changes, [{ op: 'delete', block: 'gizmo:a' }]);
});

