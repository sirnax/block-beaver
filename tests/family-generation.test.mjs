import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm, readdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { applyGeneration, checkGeneration, planGeneration } from '../src/families/generate.mjs';

const NOW = new Date('2026-10-01T12:00:00Z');

async function repo(t, files = {}) {
  const root = await mkdtemp(join(tmpdir(), 'block-beaver-gen-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  for (const [path, text] of Object.entries(files)) {
    await mkdir(dirname(join(root, path)), { recursive: true });
    await writeFile(join(root, path), text);
  }
  return root;
}

const family = (id, { floor = 0, generators = ['registry'], registry, manifests = `blocks/${id}s/*.ts`, extra = {} } = {}) => ({
  id, implementation: ['module', 'none'], fields: { type: 'object', shape: {} }, links: [], generators, hasCheck: false, floor,
  config: { id, contract: `blocks/${id}.family.ts`, manifests, ...(registry === null ? {} : { registry: registry ?? { out: `src/generated/${id}.ts` } }), ...extra },
});
const manifest = (familyId, id, { exportName = 'default', path, hash, value } = {}) => ({
  family: familyId, id, ref: `${familyId}:${id}`, graphId: `block:${familyId}:${id}`,
  path: path ?? `blocks/${familyId}s/${id}.ts`, exportName, hash: hash ?? `sha256:${familyId}-${id}`,
  value: value ?? { id, family: familyId, version: 1, name: id, description: id, rationale: 'because', implementation: { kind: 'none' } },
});

/** Fake of the public loader seam: returns a canned FamilyLoadResult and records every call. */
function fakeLoader({ families = [], manifests = [], generators = [], diagnostics = [], outputs = {}, loadedFiles = [] } = {}) {
  const calls = [];
  const load = async (args) => {
    calls.push(args);
    const result = { key: 'fake', families, manifests, generators, loadedFiles, diagnostics };
    if (args.generate) {
      result.outputs = args.generate.keys.map((key) => {
        const out = outputs[key];
        return typeof out === 'object' && out?.diagnostic ? { key, diagnostic: out.diagnostic } : { key, content: typeof out === 'function' ? out(args.generate) : out };
      });
    }
    return result;
  };
  load.calls = calls;
  return load;
}

const plan = (root, loader, extra = {}) => planGeneration({ root, config: {}, graph: { nodes: [], hashes: {} }, paths: [], label: null, now: NOW, loadFamilies: loader, ...extra });

