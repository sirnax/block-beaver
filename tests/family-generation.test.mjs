  const inputs = ['x/**/*.ts', 'y--z/*.ts'];
  const loader = fakeLoader({
    generators: Object.entries(outs).map(([name, out]) => custom(name, { out, inputs })),
    outputs: { 'custom:ts': 'body', 'custom:mjs': 'body\n', 'custom:css': 'body', 'custom:md': 'body', 'custom:html': 'body', 'custom:json': '{"a":1}', 'custom:crlf': 'a\r\nb\rc', 'custom:empty': '' },
  });
  const result = await plan(root, loader);
  assert.deepEqual(result.diagnostics, []);
  const expected = Object.fromEntries(result.outputs.map((output) => [output.key.slice('custom:'.length), output.expected]));
