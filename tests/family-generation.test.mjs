/** A custom generator over real input files, whose output changes on every real run. */
async function cached(t, { files = { 'data/one.json': '{"n":1}', 'docs/readme.md': 'hi' }, ...options } = {}) {
  const root = await repo(t, files);
  let runs = 0;
  const info = custom('gen/table.ts', { out: 'gen/table.md', inputs: ['data/*.json'], ...options });
  const loader = fakeLoader({ generators: [info], outputs: { [info.key]: () => `run ${++runs}` } });
  const settle = async () => { const result = await plan(root, loader); await applyGeneration(root, result); return result; };
  return { root, loader, info, settle, runs: () => runs };
}

test('a custom generator is skipped while its real input globs, code and output are unchanged', async (t) => {
  const { root, loader, settle } = await cached(t);
  const first = await settle();
  assert.equal(first.outputs[0].status, 'missing');
  assert.equal(generateCalls(loader).length, 1);
  assert.equal(JSON.parse(await readFile(join(root, '.blocks/cache/generators.json'), 'utf8')).schemaVersion, 1);

  const second = await settle();
  assert.equal(second.outputs[0].status, 'cached');
  assert.equal(second.outputs[0].expected, second.outputs[0].current);
  assert.equal(second.cacheUpdate, null);
  assert.equal(generateCalls(loader).length, 1, 'no child was asked to run it');
  assert.deepEqual(checkGeneration(second), []);

  await writeFile(join(root, 'docs/readme.md'), 'changed but not an input');
  assert.equal((await settle()).outputs[0].status, 'cached');
  assert.equal(generateCalls(loader).length, 1);
});

test('changing a matched input, adding a match, changing code or editing the output reruns it', async (t) => {
  const { root, loader, info, settle } = await cached(t);
  await settle();
  const runs = () => generateCalls(loader).length;

  await writeFile(join(root, 'data/one.json'), '{"n":2}');
  assert.equal((await settle()).outputs[0].status, 'stale');
  assert.equal(runs(), 2);

  await writeFile(join(root, 'data/two.json'), '{}');
  await settle();
  assert.equal(runs(), 3);

  await writeFile(join(root, 'gen/table.md'), '<!-- generated by block-beaver; do not edit -->\nhand edit\n');
  const repaired = await settle();
  assert.equal(repaired.outputs[0].status, 'stale');
  assert.equal(runs(), 4);

  info.closureHash = 'c2';
  await settle();
  assert.equal(runs(), 5);
  assert.equal((await settle()).outputs[0].status, 'cached');
});

